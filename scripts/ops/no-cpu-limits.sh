#!/bin/sh
# no-cpu-limits.sh — write the compose override that lifts every `cpus:` limit.
#
# THE FAILURE THIS EXISTS FOR
# Rootless Docker on a host that delegates only `memory pids` to the user's cgroup (a 42 seat:
# cgroup v2, `docker info` CPUCfsQuota=false) refuses any container with a CPU limit:
#   NanoCPUs can not be set, as your kernel does not support CPU CFS scheduler
# 41 services here carry one, so a fresh clone's `make up` died before anything started and the
# project could not be deployed on the machines it is graded on. Memory limits work there and
# stay: only `cpus` is lifted, and only where Docker says it cannot honour it.
#
# Read from the compose files with awk, not `docker compose config`: the Makefile calls this at
# parse time, and that would pay a compose load on every target.
#
# Caveat: finds a limit written `    cpus:` under a two-space service name in a `services:` map,
# the shape every file here uses. A differently indented one is missed and fails loudly, at `up`.
#
#   sh scripts/ops/no-cpu-limits.sh <output file>
set -eu

out="${1:?usage: no-cpu-limits.sh <output file>}"
tmp="$out.$$"
{
  printf '# Generated by scripts/ops/no-cpu-limits.sh. Not tracked: edit that, not this.\n'
  printf 'services:\n'
  awk '
    FNR == 1 { svc = ""; in_services = 0 }
    /^services:/ { in_services = 1; next }
    /^[a-zA-Z]/ { in_services = 0 }
    in_services && /^  [a-zA-Z0-9_-]+:[[:space:]]*$/ { svc = $1; sub(/:$/, "", svc) }
    in_services && /^    cpus:/ && svc != "" && !seen[svc]++ { printf "  %s:\n    cpus: 0\n", svc }
  ' orchestrators/compose/base/*.yml
} >"$tmp"
mv "$tmp" "$out"
